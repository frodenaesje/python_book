a = 10
b = 3

print(a + b) # 13
print(a - b) # 7
print(a * b) # 30
print(a // b) # 3 (integer division)
print(a / b) # 3.3333333333333335 (decimal division)
print(a % b) # 1 (modulus) 3 goes 3 times into 10, with remainder 1 (10 - 9)
print(a ** b) # 1000 (exponentiation)
