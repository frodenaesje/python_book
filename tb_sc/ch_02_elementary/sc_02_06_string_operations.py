# file: sc_02_06_string_operations.py

# 1. Creating strings
str1 = "Hello"
str2 = "world"

# 2. Printing strings
print(str1)
print(str2)

# 3. String concatenation with +
str3 = str1 + " " + str2
print(str3)

# 4. Indexing - retrieving a single character
first_char = str1[0]
second_char = str2[1]
print(first_char)
print(second_char)

# 5. String multiplication
str4 = str1 * 3
print(str4)

# 6. Common string methods
print(str3.upper())
print(str3.lower())
print(str3.title())
